/**
 * Huge documents under `heapCappedTest` (256 MB heap): a multi-gigabyte generated document is inserted into a store
 * on a real disk with the default options, which size the engine's budgets to the heap, then searched for a hot term in
 * every result mode with every hit streamed out, and in descending order, and the store is reopened. The document is a
 * promoted insert with hundreds of mid-document flushes, so this also exercises streaming posting merges over many
 * runs and segments. The whole document read back must equal the generated bytes, and so must its pretty-printed form
 * with the whitespace dropped; hit counts must equal the [StreamingExpectation].
 * `-Ddelva.heapCapped.bytes=<n>` changes the size (default 2 GiB; CI nightly may use 5 GiB).
 */
class EngineHeapCappedTest {
    private val documentBytes = System.getProperty("delva.heapCapped.bytes")?.toLong() ?: (2L shl 30)

    private class CountingOutput : OutputStream() {
        var bytes = 0L

        override fun write(b: Int) {
            bytes++
        }

        override fun write(b: ByteArray, off: Int, len: Int) {
            bytes += len
        }
    }

    /** Compares what's written with the bytes of [expected], holding neither. */
    private class ComparingOutput(private val expected: GeneratedJson) : OutputStream() {
        private val buffer = ByteArray(1 shl 16)
        var bytes = 0L

        override fun write(b: Int) = write(byteArrayOf(b.toByte()), 0, 1)

        override fun write(b: ByteArray, off: Int, len: Int) {
            var done = 0
            while (done < len) {
                val n = expected.read(buffer, 0, minOf(buffer.size, len - done))
                check(n > 0) { "output longer than the document, at byte ${bytes + done}" }
                for (i in 0 until n) check(buffer[i] == b[off + done + i]) { "output differs from the document at byte ${bytes + done + i}" }
                done += n
            }
            bytes += len
        }

        fun finish() = check(expected.read() < 0) { "output ends at byte $bytes, before the document" }
    }

    /** Drops the whitespace outside strings of formatted JSON and passes the rest on to [next]. */
    private class StrippingOutput(private val next: OutputStream) : OutputStream() {
        private val buffer = ByteArray(1 shl 16)
        private var inString = false
        private var escaped = false
        var bytes = 0L
        var lines = 0L

        override fun write(b: Int) = write(byteArrayOf(b.toByte()), 0, 1)

        override fun write(b: ByteArray, off: Int, len: Int) {
            var n = 0
            for (i in off until off + len) {
                val c = b[i].toInt()
                when {
                    inString -> when {
                        escaped -> escaped = false
                        c == '\\'.code -> escaped = true
                        c == '"'.code -> inString = false
                    }
                    c == '"'.code -> inString = true
                    c == '\n'.code -> {
                        lines++
                        continue
                    }
                    c == ' '.code || c == '\t'.code -> continue
                }
                buffer[n++] = b[i]
                if (n == buffer.size) {
                    next.write(buffer, 0, n)
                    n = 0
                }
            }
            next.write(buffer, 0, n)
            bytes += len
        }
    }

    /**
     * Live heap after a full collection, with a store open and idle, which is what the budgets bound; the
     * [LiveHeapSampler] peak, printed for information, also covers the work in progress.
     */
    private fun liveHeapBytes(): Long {
        repeat(2) {
            System.gc()
            Thread.sleep(200)
        }
        return ManagementFactory.getMemoryMXBean().heapMemoryUsage.used
    }

    private fun seconds(start: Long) = "%.1f s".format((System.nanoTime() - start) / 1e9)

    @Test
    fun `a huge document is inserted, searched and streamed out in bounded memory`() {
        val dir = Files.createTempDirectory("delva-heap")
        try {
            val options = EngineOptions()
            println(
                "heap ${options.heapBytes shr 20} MiB: memtables ${options.memtableBytes shr 20}/${options.memtableBudgetBytes shr 20} MiB, ingest ${options.ingestBudgetBytes shr 20} MiB, " +
                    "caches ${options.blockCacheBytes shr 20}+${options.fragmentCacheBytes shr 20} MiB, sorter ${options.split.sorterBytes shr 20} MiB, ${options.largeLanes} large lane(s)",
            )
            val expectation = StreamingExpectation("qty", ONum("1"))
            val one = JsonQueryValue.Num(BigDecimal.ONE)
            // One full collection a second: the run is long, and each collection costs more with a bigger live heap.
            LiveHeapSampler(intervalMillis = 1000).use { sampler ->
                Engine.open(dir, options, JdkFileSystemIo()).use { store ->
                    var start = System.nanoTime()
                    val docId = store.insert(GeneratedJson(7, BigDocProfile.CATALOG, documentBytes, expectation))
                    val v = store.indexes.versions.current()
                    println(
                        "insert ${documentBytes shr 20} MiB: ${seconds(start)}, ${store.indexes.flushes} flushes, peak memtables ${store.indexes.peakMemtableBytes shr 20} MiB " +
                            "(${store.indexes.memtableWaits} waits), ${v.postingSegments.size} posting segments (${v.postingSegments.sumOf { it.reader.heapBytes } shr 10} KiB heap), " +
                            "${v.fragmentSegments.size} fragment segments, peak live heap ${sampler.peak shr 20} MiB",
                    )
                    assertTrue(store.indexes.peakMemtableBytes <= options.memtableBudgetBytes + (8L shl 20), "memtables peaked at ${store.indexes.peakMemtableBytes}")

                    start = System.nanoTime()
                    val whole = ComparingOutput(GeneratedJson(7, BigDocProfile.CATALOG, documentBytes))
                    store.search(KeyValueQuery("qty", one, ResultMode.WHOLE_DOCUMENT)).use { result ->
                        val hits = result.iterator().asSequence().toList()
                        assertEquals(listOf(docId), hits.map { it.node.docId })
                        hits.single().writeJsonTo(whole)
                    }
                    whole.finish()
                    println("whole document: ${whole.bytes} bytes equal to the input, ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")

                    start = System.nanoTime()
                    val compared = ComparingOutput(GeneratedJson(7, BigDocProfile.CATALOG, documentBytes))
                    val pretty = StrippingOutput(compared)
                    store.search(KeyValueQuery("qty", one, ResultMode.WHOLE_DOCUMENT)).use { result ->
                        result.iterator().next().writeJsonTo(pretty, JsonFormat.PRETTY)
                    }
                    compared.finish()
                    assertTrue(pretty.lines > 0)
                    println(
                        "whole document pretty-printed: ${pretty.bytes} bytes in ${pretty.lines + 1} lines, equal to the input without whitespace, " +
                            "${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB",
                    )

                    start = System.nanoTime()
                    val out = CountingOutput()
                    var containing = 0L
                    store.search(KeyValueQuery("qty", one, ResultMode.CONTAINING_ELEMENT, limit = 1000)).use { result ->
                        for (hit in result.iterator()) {
                            containing++
                            hit.writeJsonTo(out)
                        }
                    }
                    println("containing: $containing hits, ${out.bytes} bytes of JSON, ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
                    assertEquals(expectation.containingHits, containing)

                    start = System.nanoTime()
                    val outermost = store.search(KeyValueQuery("qty", one, ResultMode.CONTAINING_ELEMENT, NestedHits.OUTERMOST_ONLY, limit = 1000)).use { result ->
                        result.iterator().asSequence().count().toLong()
                    }
                    println("outermost: $outermost hits, ${seconds(start)}")
                    assertEquals(expectation.outermostHits, outermost)

                    // Descending: the same hits last first, read in chunks of a bounded number of hits.
                    for (nested in NestedHits.entries) {
                        start = System.nanoTime()
                        val query = KeyValueQuery("qty", one, ResultMode.CONTAINING_ELEMENT, nested, limit = 1000)
                        var ascendingSum = 0L
                        store.search(query).use { result -> for (hit in result.iterator()) ascendingSum += hit.node.nodePre }
                        var count = 0L
                        var sum = 0L
                        var previous = Long.MAX_VALUE
                        var passes = 0L
                        store.search(query.copy(order = SearchOrder.DESCENDING)).use { result ->
                            for (hit in result.iterator()) {
                                check(hit.node.nodePre < previous) { "descending hit ${hit.node} after pre $previous" }
                                previous = hit.node.nodePre
                                sum += hit.node.nodePre
                                count++
                            }
                            passes = ((result as EngineSearchResult).source as QueryExecutor).passesForOrder
                        }
                        println("descending $nested: $count hits in ${passes + 1} passes, ${seconds(start)} with the ascending read, peak live heap ${sampler.peak shr 20} MiB")
                        assertEquals(if (nested == NestedHits.ALL) expectation.containingHits else expectation.outermostHits, count)
                        assertEquals(ascendingSum, sum)
                    }
                }
                var start = System.nanoTime()
                Engine.open(dir, options, JdkFileSystemIo()).use { store ->
                    val stats = store.recoveryStats
                    println("reopen: ${seconds(start)}, ${stats.replayedCommits} COMMITs and ${stats.replayedBytes shr 20} MiB of lanes replayed")
                    // Only what wasn't flushed: the lane bytes after the last flush's watermark, whatever the size.
                    assertTrue(stats.replayedCommits <= 1)
                    assertTrue(stats.replayedBytes <= 2 * options.memtableBytes + 4L * options.split.sorterBytes, "replayed ${stats.replayedBytes} lane bytes")
                    start = System.nanoTime()
                    val count = store.search(KeyValueQuery("qty", one, ResultMode.CONTAINING_ELEMENT, limit = 1000)).use { result -> result.iterator().asSequence().count().toLong() }
                    assertEquals(expectation.containingHits, count)
                    val live = liveHeapBytes()
                    println("containing after reopen: ${seconds(start)}, live heap ${live shr 20} MiB, sampled peak ${sampler.peak shr 20} MiB")
                    assertTrue(live < 200L shl 20, "live heap is ${live shr 20} MiB while a store is open on a 2 GiB document")
                }
            }
        } finally {
            dir.toFile().deleteRecursively()
        }
    }

    @Test
    fun `a whole-document hit of millions of fragments sizes itself in bounded memory`() {
        // 64-byte fragments: the document's fragment-index entries, held at once, would take more than the heap.
        val elements = System.getProperty("delva.heapCapped.bytes")?.toLong()?.div(64) ?: 32_000_000L
        val dir = Files.createTempDirectory("delva-fragments-heap")
        try {
            LiveHeapSampler().use { sampler ->
                Engine.open(dir, EngineOptions(CreationOptions(fragmentBytes = 64)), JdkFileSystemIo()).use { store ->
                    var start = System.nanoTime()
                    val chunks = sequence {
                        yield("{\"k\":1,\"items\":[")
                        for (i in 0 until elements) yield(if (i == 0L) "$i" else ",$i")
                        yield("]}")
                    }
                    store.insert(ChunkedInputStream(chunks))
                    println("$elements elements inserted in ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
                    start = System.nanoTime()
                    val size = store.search(KeyValueQuery("k", JsonQueryValue.Num(1), ResultMode.WHOLE_DOCUMENT)).use { result ->
                        result.nextPage()!!.hits.single().encodedSize
                    }
                    println("  whole-document hit: $size encoded bytes, ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
                    assertTrue(size > elements, "$size bytes")
                }
                assertTrue(sampler.peak < 200L shl 20, "live heap peaked at ${sampler.peak shr 20} MiB")
            }
        } finally {
            dir.toFile().deleteRecursively()
        }
    }

    @Test
    fun `a type-driven search over more typed objects than the heap holds longs runs in bounded memory`() {
        // One document of {"k":1} objects, every one typed: a list of their pres would need 8 bytes each, more than the
        // heap. Object i is at pre 2 + 2i, after the root and the array.
        // A doubling LongArray of 20M pres needs a 256 MiB copy.
        val objects = System.getProperty("delva.heapCapped.typedObjects")?.toLong() ?: 20_000_000L
        val dir = Files.createTempDirectory("delva-typed-heap")
        try {
            LiveHeapSampler().use { sampler ->
                // Small fragments, so that locating each object to type it reads a few objects, not a 64 KiB PART.
                Engine.open(dir, EngineOptions(CreationOptions(fragmentBytes = 256), typeQueryPlan = TypeQueryPlan.TYPE_DRIVEN), JdkFileSystemIo()).use { store ->
                    var start = System.nanoTime()
                    val chunks = sequence {
                        yield("{\"items\":[")
                        for (i in 0 until objects) yield(if (i == 0L) "{\"k\":1}" else ",{\"k\":1}")
                        yield("]}")
                    }
                    val docId = store.insert(ChunkedInputStream(chunks))
                    var assigned = 0L
                    while (assigned < objects) {
                        val batch = minOf(100_000L, objects - assigned)
                        store.assignTypes(List(batch.toInt()) { NodeRef(docId, 2 + 2 * (assigned + it)) to "Item" })
                        assigned += batch
                    }
                    println("$objects objects inserted and typed in ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
                    // Ascending only: descending walks a document once per earlier chunk of hits, so one document of 20M hits
                    // would take hours whatever the plan.
                    for (order in listOf(SearchOrder.ASCENDING)) {
                        start = System.nanoTime()
                        val query = KeyValueQuery("k", JsonQueryValue.Num(1), ResultMode.CONTAINING_ELEMENT, limit = 1000, type = "Item", order = order)
                        val hits = store.search(query).use { result ->
                            result.iterator().asSequence().count().toLong().also { assertTrue((result as EngineSearchResult).executor.stats.typeDriven) }
                        }
                        println("  type-driven $order: $hits hits, ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
                        assertEquals(objects, hits)
                    }
                }
                assertTrue(sampler.peak < 200L shl 20, "live heap peaked at ${sampler.peak shr 20} MiB")
            }
        } finally {
            dir.toFile().deleteRecursively()
        }
    }
}
