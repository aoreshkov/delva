package app.oreshkov.delva.internal.engine

import app.oreshkov.delva.CompareOperand
import app.oreshkov.delva.DiffOptions
import app.oreshkov.delva.DocId
import app.oreshkov.delva.NodeRef
import app.oreshkov.delva.internal.LiveHeapSampler
import app.oreshkov.delva.internal.io.JdkFileSystemIo
import app.oreshkov.delva.internal.log.LogFiles
import app.oreshkov.delva.testkit.generate.BigDocProfile
import app.oreshkov.delva.testkit.generate.GeneratedJson
import java.io.FilterInputStream
import java.io.InputStream
import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/**
 * Comparisons under `heapCappedTest` (256 MB heap): huge generated documents on a real disk are compared with copies
 * of themselves, stored and given as JSON streams, and with copies that differ in a few digits. A MIXED document
 * (records, 900-level chains, multi-MiB strings) exercises stubs, hashes and chunked strings; a WIDE_OBJECT document is
 * one split object whose parts' key ranges interleave (`k1` < `k10` < `k100` …), so its members are merged across all
 * parts. Live heap must stay bounded whatever the sizes. `-Ddelva.heapCapped.bytes=<n>` scales both (default 2 GiB:
 * 256 MiB mixed, 16 MiB wide).
 */
class CompareHeapCappedTest {
    private val scale = System.getProperty("delva.heapCapped.bytes")?.toLong() ?: (2L shl 30)
    private val mixedBytes = scale / 8
    private val wideBytes = scale / 128

    /** The generated bytes with the first digit `0`–`8` right after a `:` at or after each of [offsets] incremented: still valid JSON with the same keys. */
    private class Edited(source: InputStream, offsets: List<Long>) : FilterInputStream(source) {
        private val pending = ArrayDeque(offsets.sorted())
        private var position = 0L
        private var previous = 0

        override fun read(): Int {
            val b = ByteArray(1)
            return if (read(b, 0, 1) < 0) -1 else b[0].toInt() and 0xFF
        }

        override fun read(b: ByteArray, off: Int, len: Int): Int {
            val n = super.read(b, off, len)
            if (n <= 0) return n
            for (i in 0 until n) {
                val at = pending.firstOrNull()
                if (at != null && position + i >= at && previous == COLON && b[off + i] in DIGIT_0..DIGIT_8) {
                    b[off + i]++
                    pending.removeFirst()
                }
                previous = b[off + i].toInt()
            }
            position += n
            return n
        }

        private companion object {
            const val COLON = ':'.code
            const val DIGIT_0 = '0'.code.toByte()
            const val DIGIT_8 = '8'.code.toByte()
        }
    }

    private fun seconds(start: Long) = "%.1f s".format((System.nanoTime() - start) / 1e9)

    private fun stored(docId: DocId) = CompareOperand.Stored(NodeRef(docId, 0))

    private fun check(store: Engine, sampler: LiveHeapSampler, profile: BigDocProfile, bytes: Long, seed: Long) {
        fun generated() = GeneratedJson(seed, profile, bytes)
        val edits = listOf(bytes / 7, bytes / 2, bytes - bytes / 5)
        var start = System.nanoTime()
        val a = store.insert(generated())
        val copy = store.insert(generated())
        val edited = store.insert(Edited(generated(), edits))
        println("$profile ${bytes shr 20} MiB: three inserts ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
        val stats = store.compareStats

        start = System.nanoTime()
        assertTrue(store.isEqual(stored(a), stored(copy)))
        println("  isEqual of equal stored documents: ${seconds(start)}, ${stats.treesBuilt.sum()} trees, ${stats.partIndexesBuilt.sum()} part indexes, peak live heap ${sampler.peak shr 20} MiB")

        start = System.nanoTime()
        assertFalse(store.isEqual(stored(a), stored(edited)))
        println("  isEqual of different stored documents: ${seconds(start)} (${stats.unequalWithoutReading.sum()} answered from hashes)")

        start = System.nanoTime()
        val skippedBefore = stats.skippedByHash.sum()
        val differences = store.diff(stored(a), stored(edited), DiffOptions(maxValueBytes = 256))
        println("  diff: ${differences.size} differences ${differences.map { "${it.kind} ${it.path.take(80)}" }}, ${seconds(start)}, ${stats.skippedByHash.sum() - skippedBefore} subtrees skipped by hash, peak live heap ${sampler.peak shr 20} MiB")
        // Each edit changes a number, or the digit after a colon inside a string.
        assertTrue(differences.size in 1..edits.size, "${differences.size} differences")
        assertEquals(differences.map { it.path to it.kind }, store.diff(stored(copy), stored(edited), DiffOptions(maxValueBytes = 256)).map { it.path to it.kind })

        start = System.nanoTime()
        assertTrue(store.isEqual(CompareOperand.JsonStream(generated()), stored(copy)))
        println("  isEqual of a stored document and a JSON stream: ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
        start = System.nanoTime()
        val fromStream = store.diff(stored(a), CompareOperand.JsonStream(Edited(generated(), edits)), DiffOptions(maxValueBytes = 256))
        assertEquals(differences.map { it.path to it.kind }, fromStream.map { it.path to it.kind })
        println("  diff with a JSON stream: ${seconds(start)}, peak live heap ${sampler.peak shr 20} MiB")
    }

    @Test
    fun `huge values are compared and diffed in bounded memory`() {
        val dir = Files.createTempDirectory("delva-compare-heap")
        try {
            val options = EngineOptions()
            println("heap ${options.heapBytes shr 20} MiB: compare cache ${options.compareCacheBytes shr 20} MiB, literal memory ${options.literalMemoryBytes shr 20} MiB")
            LiveHeapSampler().use { sampler ->
                Engine.open(dir, options, JdkFileSystemIo()).use { store ->
                    check(store, sampler, BigDocProfile.MIXED, mixedBytes, seed = 11)
                    check(store, sampler, BigDocProfile.WIDE_OBJECT, wideBytes, seed = 12)
                    assertTrue(Files.list(dir.resolve(LogFiles.TMP_DIR)).use { it.count() } == 0L, "temporary files left")
                }
                assertTrue(sampler.peak < 200L shl 20, "live heap peaked at ${sampler.peak shr 20} MiB")
            }
        } finally {
            dir.toFile().deleteRecursively()
        }
    }
}
